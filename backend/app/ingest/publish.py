"""Validate, load and publish dataset and document versions.

Publishing a dataset version, all in ONE database transaction:
  1. validate the manifest, then the CSV rows against it;
  2. check relationships against the referenced datasets' *published* versions;
  3. create a typed table datasets.t_<source>_v<n> and bulk-load the rows (COPY);
  4. build the value index (distinct values + aliases);
  5. mark the new version published and the previous one superseded.
If any step fails, Postgres rolls everything back, including the CREATE TABLE.

Idempotent: re-publishing identical content (same SHA-256) is a no-op.
Invalid uploads are recorded as an `invalid` version with their issues, so a steward can review
them later; they never become visible to answers.
"""

import hashlib
import json
from dataclasses import dataclass, field
from datetime import UTC, date, datetime

import yaml
from sqlalchemy import func, select, text
from sqlalchemy.orm import Session

from app import audit
from app.documents.index import index_document
from app.ingest.manifest import Column, Manifest, parse_manifest
from app.ingest.validate import Issue, validate_csv
from app.models import (
    DocumentContent,
    Source,
    SourceKind,
    SourceStatus,
    SourceVersion,
    User,
    ValueIndexEntry,
    VersionStatus,
)

DATASET_SCHEMA = "datasets"
PG_TYPES = {
    "string": "text",
    "integer": "bigint",
    "decimal": "numeric",
    "boolean": "boolean",
    "date": "date",
    "timestamp": "timestamp",  # local store time, no timezone (see data-quality notes)
}
MAX_REPORTED_REFERENCE_ERRORS = 20


@dataclass
class PublishResult:
    source: str
    status: str  # "published", "unchanged" or "invalid"
    version: int | None = None
    issues: list[str] = field(default_factory=list)
    issue_count: int = 0
    row_count: int | None = None
    table: str | None = None


# ----------------------------------------------------------------------------- helpers


def physical_table_name(source: Source, version: int) -> str:
    """Generated by code from the source's UUID, never from user input."""
    return f"t_{source.id.hex[:12]}_v{version}"


def _quote(identifier: str) -> str:
    # Identifiers were validated against a strict pattern; quoting is a second layer.
    return '"' + identifier.replace('"', '""') + '"'


def _sha256(*parts: bytes) -> str:
    digest = hashlib.sha256()
    for part in parts:
        digest.update(hashlib.sha256(part).digest())
    return digest.hexdigest()


def _lock_source(db: Session, slug: str, kind: SourceKind) -> Source | None:
    """Row lock: a second publish of the same source waits here until the first commits."""
    source = db.scalar(select(Source).where(Source.slug == slug).with_for_update())
    if source is None or source.kind != kind or source.status != SourceStatus.ACTIVE:
        return None
    return source


def _next_version(db: Session, source: Source) -> int:
    current = db.scalar(
        select(func.max(SourceVersion.version)).where(SourceVersion.source_id == source.id)
    )
    return (current or 0) + 1


def _existing_with_hash(db: Session, source: Source, content_hash: str) -> SourceVersion | None:
    return db.scalar(
        select(SourceVersion).where(
            SourceVersion.source_id == source.id,
            SourceVersion.content_hash == content_hash,
            SourceVersion.status.in_([VersionStatus.PUBLISHED, VersionStatus.SUPERSEDED]),
        )
    )


def _previously_invalid(db: Session, source: Source, content_hash: str) -> SourceVersion | None:
    return db.scalar(
        select(SourceVersion).where(
            SourceVersion.source_id == source.id,
            SourceVersion.content_hash == content_hash,
            SourceVersion.status == VersionStatus.INVALID,
        )
    )


def published_version(db: Session, slug: str) -> SourceVersion | None:
    return db.scalar(
        select(SourceVersion)
        .join(Source)
        .where(Source.slug == slug, SourceVersion.status == VersionStatus.PUBLISHED)
    )


def _mark_published(db: Session, source: Source, version: SourceVersion) -> None:
    db.query(SourceVersion).filter(
        SourceVersion.source_id == source.id, SourceVersion.status == VersionStatus.PUBLISHED
    ).update({SourceVersion.status: VersionStatus.SUPERSEDED})
    db.flush()  # the one-published-version index is checked per statement
    version.status = VersionStatus.PUBLISHED
    version.published_at = datetime.now(UTC)


def _record_invalid(
    db: Session, source: Source, content_hash: str, issues: list[str], count: int
) -> int:
    number = _next_version(db, source)
    db.add(
        SourceVersion(
            source_id=source.id,
            version=number,
            status=VersionStatus.INVALID,
            content_hash=content_hash,
            meta={"issues": issues, "issue_count": count},
        )
    )
    return number


# ----------------------------------------------------------------------------- datasets


def _check_references(db: Session, manifest: Manifest, rows: list[tuple]) -> list[Issue]:
    issues: list[Issue] = []
    names = [c.name for c in manifest.columns]
    for rel in manifest.relationships:
        target = published_version(db, rel.target_source)
        if target is None:
            issues.append(
                Issue(None, rel.column, f"{rel.target_source} has no published version yet")
            )
            continue
        target_cols = {c["name"] for c in target.meta["manifest"]["columns"]}
        if rel.target_column not in target_cols:
            issues.append(Issue(None, rel.column, f"{rel.references} does not exist"))
            continue
        table = f"{DATASET_SCHEMA}.{_quote(target.meta['table'])}"
        known = set(db.scalars(text(f"SELECT DISTINCT {_quote(rel.target_column)} FROM {table}")))  # noqa: S608 - identifiers generated/validated
        index = names.index(rel.column)
        for row_number, row in enumerate(rows, start=2):
            if row[index] is not None and row[index] not in known:
                issues.append(
                    Issue(row_number, rel.column, f"{row[index]!r} not found in {rel.references}")
                )
                if len(issues) >= MAX_REPORTED_REFERENCE_ERRORS:
                    return issues
    for ref in sorted(manifest.external_metric_refs()):
        source_slug, metric = ref.split(".")
        target = published_version(db, source_slug)
        if target is None:
            issues.append(
                Issue(None, None, f"derived metric uses {ref}, but {source_slug} is not published")
            )
            continue
        target_metrics = {m["name"] for m in target.meta["manifest"].get("metrics", [])}
        if metric not in target_metrics:
            issues.append(Issue(None, None, f"derived metric uses unknown metric {ref}"))
    return issues


def _alias_issues(manifest: Manifest, rows: list[tuple]) -> list[Issue]:
    issues = []
    names = [c.name for c in manifest.columns]
    for col in manifest.columns:
        if col.aliases:
            present = {row[names.index(col.name)] for row in rows}
            for alias, canonical in col.aliases.items():
                if canonical not in present:
                    issues.append(
                        Issue(
                            None,
                            col.name,
                            f"alias {alias!r} points to {canonical!r}, which is not in the data",
                        )
                    )
    return issues


def _create_and_load(db: Session, table: str, manifest: Manifest, rows: list[tuple]) -> None:
    columns_sql = ", ".join(
        f"{_quote(c.name)} {PG_TYPES[c.type]}{'' if c.nullable else ' NOT NULL'}"
        for c in manifest.columns
    )
    pk_sql = ", ".join(_quote(k) for k in manifest.primary_key)
    qualified = f"{DATASET_SCHEMA}.{_quote(table)}"
    db.execute(text(f"CREATE TABLE {qualified} ({columns_sql}, PRIMARY KEY ({pk_sql}))"))
    column_list = ", ".join(_quote(c.name) for c in manifest.columns)
    # COPY is Postgres' bulk loader: one streamed command instead of one INSERT per row.
    raw = db.connection().connection.dbapi_connection
    with raw.cursor() as cur, cur.copy(f"COPY {qualified} ({column_list}) FROM STDIN") as copy:
        for row in rows:
            copy.write_row(row)


def _build_value_index(
    db: Session, version: SourceVersion, manifest: Manifest, rows: list[tuple]
) -> int:
    names = [c.name for c in manifest.columns]
    entries: list[ValueIndexEntry] = []
    indexed: list[Column] = [c for c in manifest.columns if c.value_index]
    for col in indexed:
        values = sorted(
            {str(r[names.index(col.name)]) for r in rows if r[names.index(col.name)] is not None}
        )
        for v in values:
            entries.append(
                ValueIndexEntry(
                    source_version_id=version.id,
                    column_name=col.name,
                    value=v,
                    value_norm=v.lower(),
                    canonical=v,
                )
            )
        for alias, canonical in sorted(col.aliases.items()):
            entries.append(
                ValueIndexEntry(
                    source_version_id=version.id,
                    column_name=col.name,
                    value=alias,
                    value_norm=alias.lower(),
                    canonical=canonical,
                    is_alias=True,
                )
            )
    db.add_all(entries)
    return len(entries)


def publish_dataset(
    db: Session, manifest_data: dict, csv_bytes: bytes, actor: User | None = None
) -> PublishResult:
    slug = str(manifest_data.get("source", "?")) if isinstance(manifest_data, dict) else "?"
    manifest, problems = parse_manifest(manifest_data)
    if manifest is None:
        return PublishResult(slug, "invalid", issues=problems, issue_count=len(problems))

    source = _lock_source(db, manifest.source, SourceKind.DATASET)
    if source is None:
        db.rollback()
        msg = f"dataset {manifest.source!r} is not registered (an administrator registers sources)"
        return PublishResult(manifest.source, "invalid", issues=[msg], issue_count=1)

    canonical_manifest = json.dumps(manifest.model_dump(mode="json"), sort_keys=True).encode()
    content_hash = _sha256(canonical_manifest, csv_bytes)
    if existing := _existing_with_hash(db, source, content_hash):
        db.rollback()
        return PublishResult(manifest.source, "unchanged", version=existing.version)
    if rejected := _previously_invalid(db, source, content_hash):
        db.rollback()  # same broken file again: report the stored issues, record nothing new
        return PublishResult(
            manifest.source,
            "invalid",
            rejected.version,
            rejected.meta["issues"],
            rejected.meta["issue_count"],
        )

    checked = validate_csv(manifest, csv_bytes)
    issues, count = [str(i) for i in checked.issues], checked.issue_count
    if checked.ok:
        extra = _alias_issues(manifest, checked.rows) + _check_references(
            db, manifest, checked.rows
        )
        issues, count = [str(i) for i in extra], len(extra)
    if count:
        number = _record_invalid(db, source, content_hash, issues, count)
        audit.record(db, actor, "version.invalid", f"{manifest.source} v{number}", issues=count)
        db.commit()
        return PublishResult(manifest.source, "invalid", number, issues, count)

    number = _next_version(db, source)
    table = physical_table_name(source, number)
    version = SourceVersion(
        source_id=source.id, version=number, status=VersionStatus.READY, content_hash=content_hash
    )
    db.add(version)
    db.flush()
    _create_and_load(db, table, manifest, checked.rows)
    indexed = _build_value_index(db, version, manifest, checked.rows)
    version.meta = {
        "manifest": manifest.model_dump(mode="json"),
        "table": table,
        "row_count": len(checked.rows),
        "value_index_entries": indexed,
    }
    _mark_published(db, source, version)
    audit.record(
        db, actor, "version.publish", f"{manifest.source} v{number}", rows=len(checked.rows)
    )
    db.commit()
    return PublishResult(
        manifest.source, "published", number, row_count=len(checked.rows), table=table
    )


# ----------------------------------------------------------------------------- documents


def _split_front_matter(raw: str) -> tuple[dict, str]:
    if not raw.startswith("---"):
        raise ValueError("document must start with a '---' metadata block")
    _, front, body = raw.split("---", 2)
    meta = yaml.safe_load(front) or {}
    if not isinstance(meta, dict):
        raise ValueError("metadata block must be key: value pairs")
    return meta, body.strip() + "\n"


def publish_document(db: Session, content: bytes, actor: User | None = None) -> PublishResult:
    try:
        meta, body = _split_front_matter(content.decode("utf-8"))
    except (UnicodeDecodeError, ValueError, yaml.YAMLError) as e:
        return PublishResult("?", "invalid", issues=[str(e)], issue_count=1)
    missing = [k for k in ("doc_id", "version", "title", "effective_date") if k not in meta]
    slug = str(meta.get("doc_id", "?"))
    if missing:
        return PublishResult(
            slug, "invalid", issues=[f"metadata is missing {missing}"], issue_count=1
        )

    source = _lock_source(db, slug, SourceKind.DOCUMENT)
    if source is None:
        db.rollback()
        msg = f"document {slug!r} is not registered (an administrator registers sources)"
        return PublishResult(slug, "invalid", issues=[msg], issue_count=1)

    content_hash = _sha256(content)
    if existing := _existing_with_hash(db, source, content_hash):
        db.rollback()
        return PublishResult(slug, "unchanged", version=existing.version)

    expected = _next_version(db, source)
    if int(meta["version"]) != expected:
        db.rollback()
        msg = f"document says version {meta['version']}, but the next version is {expected}"
        return PublishResult(slug, "invalid", issues=[msg], issue_count=1)

    clean_meta = {k: (v.isoformat() if isinstance(v, date) else v) for k, v in meta.items()}
    version = SourceVersion(
        source_id=source.id,
        version=expected,
        status=VersionStatus.READY,
        content_hash=content_hash,
        meta=clean_meta,
    )
    db.add(version)
    db.flush()
    db.add(DocumentContent(source_version_id=version.id, body=body))
    # Same transaction: the version becomes visible together with its search index.
    chunks = index_document(db, version, body)
    _mark_published(db, source, version)
    audit.record(db, actor, "version.publish", f"{slug} v{expected}", chunks=chunks)
    db.commit()
    return PublishResult(slug, "published", expected)
