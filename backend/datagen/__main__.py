"""Write the reference dataset as CSV files.

Usage (from backend/):
    uv run python -m datagen                 # Stage A: ../data/reference/tables/*.csv
    uv run python -m datagen --stage b       # Stage B additions: ../data/stage_b/tables/*.csv
    uv run python -m datagen --stage c       # Stage C additions: tables, manifests, documents
    uv run python -m datagen --out /tmp/x    # write somewhere else
"""

import argparse
import csv
from pathlib import Path

from datagen.catalog import PRODUCTS, STORES
from datagen.generate import generate

DATA = Path(__file__).resolve().parents[2] / "data"
DEFAULT_OUT = DATA / "reference" / "tables"
STAGE_B_OUT = DATA / "stage_b" / "tables"


def _fmt(value: object) -> str:
    """Stable text formatting so files are byte-identical across runs and machines."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return f"{value:.2f}"
    if hasattr(value, "isoformat"):
        return value.isoformat()
    return str(value)


def _write(path: Path, header: list[str], rows: list[list[object]]) -> None:
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(header)
        writer.writerows([[_fmt(v) for v in row] for row in rows])


def write_all(out: Path) -> dict[str, int]:
    out.mkdir(parents=True, exist_ok=True)
    lines, returns = generate()

    _write(
        out / "stores.csv",
        ["store_id", "store_name", "country", "region", "channel", "opened_date"],
        [[s.store_id, s.store_name, s.country, s.region, s.channel, s.opened_date] for s in STORES],
    )
    _write(
        out / "products.csv",
        [
            "product_id",
            "sku",
            "product_name",
            "category",
            "list_price",
            "status",
            "discontinued_date",
        ],
        [
            [
                p.product_id,
                p.sku,
                p.product_name,
                p.category,
                p.list_price,
                p.status,
                p.discontinued_date,
            ]
            for p in PRODUCTS
        ],
    )
    _write(
        out / "transactions.csv",
        [
            "line_id",
            "invoice_no",
            "line_no",
            "invoice_date",
            "store_id",
            "product_id",
            "customer_id",
            "quantity",
            "unit_price",
            "promo_code",
            "is_cancellation",
        ],
        [
            [
                x.line_id,
                x.invoice_no,
                x.line_no,
                x.invoice_date,
                x.store_id,
                x.product_id,
                x.customer_id,
                x.quantity,
                x.unit_price,
                x.promo_code,
                x.is_cancellation,
            ]
            for x in lines
        ],
    )
    _write(
        out / "returns.csv",
        [
            "return_id",
            "invoice_no",
            "line_no",
            "return_date",
            "store_id",
            "product_id",
            "quantity",
            "refund_amount",
            "reason",
        ],
        [
            [
                r.return_id,
                r.invoice_no,
                r.line_no,
                r.return_date,
                r.store_id,
                r.product_id,
                r.quantity,
                r.refund_amount,
                r.reason,
            ]
            for r in returns
        ],
    )
    return {
        "stores": len(STORES),
        "products": len(PRODUCTS),
        "transactions": len(lines),
        "returns": len(returns),
    }


def write_stage_b(out: Path) -> dict[str, int]:
    from datagen.stage_b import generate_stage_b

    out.mkdir(parents=True, exist_ok=True)
    counts = {}
    for name, table in generate_stage_b().items():
        _write(out / f"{name}.csv", table.header, table.rows)
        counts[name] = len(table.rows)
    return counts


def write_stage_c(root: Path) -> dict[str, int]:
    """Stage C writes its manifests, grants and documents too: each table is defined once in
    datagen/stage_c.py, so the CSV and the manifest can't disagree."""
    import yaml

    from datagen.stage_c import generate_stage_c
    from datagen.stage_c_docs import generate_documents

    tables = generate_stage_c()
    documents = generate_documents()
    for sub in ("tables", "manifests", "documents"):
        (root / sub).mkdir(parents=True, exist_ok=True)
        for old in (root / sub).iterdir():  # a table or document removed must not linger
            old.unlink()
    counts = {}
    for name, table in tables.items():
        _write(root / "tables" / f"{name}.csv", table.header, table.rows)
        text = "# Dataset manifest (Stage C). Synthetic. Generated by datagen/stage_c.py.\n"
        text += yaml.safe_dump(table.manifest, sort_keys=False, allow_unicode=True, width=100)
        (root / "manifests" / f"{name}.yaml").write_text(text, encoding="utf-8")
        counts[name] = len(table.rows)
    for doc in documents:
        (root / "documents" / doc.filename).write_text(doc.text, encoding="utf-8")
    grants = {name: t.readers for name, t in tables.items()}
    grants |= {doc.doc_id: doc.readers for doc in documents}
    header = (
        "# Stage C access grants: the sources added on top of Stages A and B.\n"
        "# Generated by datagen (stage_c.py, stage_c_docs.py). Synthetic.\n"
    )
    (root / "access.yaml").write_text(
        header + yaml.safe_dump({"grants": grants}, sort_keys=False, default_flow_style=None),
        encoding="utf-8",
    )
    counts["(documents)"] = len(documents)
    return counts


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--stage", choices=["a", "b", "c"], default="a")
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    if args.stage == "c":
        args.out = args.out or DATA / "stage_c"
        counts = write_stage_c(args.out)
        for name, n in counts.items():
            print(f"{name:<22} {n:>7}")
        return
    if args.stage == "b":
        args.out = args.out or STAGE_B_OUT
        counts = write_stage_b(args.out)
    else:
        args.out = args.out or DEFAULT_OUT
        counts = write_all(args.out)
    for table, n in counts.items():
        print(f"{table:<20} {n:>6} rows -> {args.out / (table + '.csv')}")


if __name__ == "__main__":
    main()
